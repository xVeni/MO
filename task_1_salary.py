# Вводим зарплату с клавиатуры
salary = float(input("Введите зарплату: "))

# Вводим стаж с клавиатуры
experience = float(input("Введите стаж: "))

# Сначала считаем, что надбавки нет
percent = 0

# Если стаж от 2 до 5 лет, надбавка 2%
if experience >= 2 and experience < 5:
    percent = 2

# Если стаж от 5 до 10 лет, надбавка 5%
elif experience >= 5 and experience <= 10:
    percent = 5

# Если стаж меньше 2 лет или больше 10 лет,
# надбавка остаётся 0%

# Рассчитываем сумму надбавки
bonus = salary * percent / 100

# Рассчитываем сумму к выплате
total = salary + bonus

# Выводим процент надбавки
print("Надбавка:", percent, "%")

# Выводим сумму надбавки
print("Сумма надбавки:", bonus)

# Выводим итоговую сумму к выплате
print("Сумма к выплате:", total)